#!/usr/bin/env python3
"""
P4OS - Mensajes: the TL schema in C.

    tl_gen.py schema/layer234.tl ../main

Writes main/tl_schema.h and main/tl_schema.c from the subset of the schema
(tl_subset.py). Nothing of TL is written by hand in the app: the reader and
the writer of mj_tl.c are one walk over these tables, so a constructor the
server sends is read the same whether the app uses it or only has to step
over it.

  tl_schema.h   TLC_<name>: every constructor's and function's id, the dots
                as underscores (TLC_messages_getHistory);
                TLN_<field>: one number per field name, shared by every
                constructor (TLN_id is the id of a message and of a user),
                which is how the app asks for a field;
                MJ_LAYER: the layer the subset was cut from.
  tl_schema.c   the tables: types, fields, constructors, the constructors
                sorted by id, and the names (for the log).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tl_schema  # noqa: E402

KINDS = {
    '#': 'TLK_FLAGS', 'int': 'TLK_INT', 'long': 'TLK_LONG', 'double': 'TLK_DOUBLE',
    'string': 'TLK_STRING', 'bytes': 'TLK_BYTES', 'int128': 'TLK_INT128',
    'int256': 'TLK_INT256', 'Bool': 'TLK_BOOL', 'true': 'TLK_TRUE',
}


def cname(n):
    return re.sub(r'[^A-Za-z0-9_]', '_', n)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, outdir = sys.argv[1:]
    text = open(src, encoding='utf-8').read()
    m = re.search(r'//\s*LAYER\s+(\d+)', text)
    layer = int(m.group(1)) if m else 0
    combs = tl_schema.parse(text)
    sch = tl_schema.Schema(combs)

    # boxed types, in order of first appearance
    btypes = []
    for c in combs:
        if c.result not in btypes and not c.is_func:
            btypes.append(c.result)
    btype_idx = {t: i for i, t in enumerate(btypes)}
    ctor_idx = {c.name: i for i, c in enumerate(combs)}

    # field names
    fnames = []
    for c in combs:
        for f in c.fields:
            if f.name not in fnames:
                fnames.append(f.name)
    fname_idx = {n: i + 1 for i, n in enumerate(fnames)}   # 0 is "no field"

    # types table (deduplicated)
    types = []
    type_idx = {}

    def tindex(t):
        if t in type_idx:
            return type_idx[t]
        if t in KINDS:
            ent = (KINDS[t], 0)
        else:
            mm = re.match(r'^([Vv])ector<(.+)>$', t)
            if mm:
                sub = tindex(mm.group(2))
                ent = ('TLK_VEC' if mm.group(1) == 'V' else 'TLK_BVEC', sub)
            elif t.startswith('!') or t in ('X', 'Object'):
                ent = ('TLK_ANY', 0)
            elif t.startswith('%'):
                ent = ('TLK_BARE', ctor_idx[t[1:]])
            elif t in btype_idx:
                ent = ('TLK_OBJ', btype_idx[t])
            elif t in ctor_idx:
                ent = ('TLK_BARE', ctor_idx[t])
            else:
                ent = ('TLK_ANY', 0)   # a type the subset left out: read as any object
        types.append(ent)
        type_idx[t] = len(types) - 1
        return type_idx[t]

    fields = []
    for c in combs:
        flag_pos = {f.name: i for i, f in enumerate(c.fields) if f.type == '#'}
        for f in c.fields:
            ti = tindex(f.type)
            fi = flag_pos[f.flag_field] if f.flag_field else -1
            bit = f.flag_bit if f.flag_field else 0
            fields.append((fname_idx[f.name], ti, fi, bit))

    # names blob
    blob = bytearray()
    name_off = {}

    def add_name(n):
        if n in name_off:
            return name_off[n]
        name_off[n] = len(blob)
        blob.extend(n.encode() + b'\0')
        return name_off[n]

    for c in combs:
        add_name(c.name)
    for n in fnames:
        add_name(n)

    h = []
    h.append('/*\n * P4OS - Mensajes: the TL schema, layer %d. GENERATED by tools/tl_gen.py\n'
             ' * from tools/schema/layer%d.tl: do not edit by hand.\n */\n' % (layer, layer))
    h.append('#pragma once\n#include <stdint.h>\n\n')
    h.append('#define MJ_LAYER %d\n' % layer)
    h.append('#define TL_NCTORS %d\n#define TL_NFIELDS %d\n#define TL_NTYPES %d\n#define TL_NBOXED %d\n#define TL_NNAMES %d\n\n'
             % (len(combs), len(fields), len(types), len(btypes), len(fnames) + 1))
    h.append('/* constructors and functions */\n')
    for c in combs:
        h.append('#define TLC_%s 0x%08xu\n' % (cname(c.name), c.id))
    h.append('\n/* boxed types */\nenum {\n')
    for i, t in enumerate(btypes):
        h.append('    TLT_%s = %d,\n' % (cname(t), i))
    h.append('};\n\n/* field names */\nenum {\n    TLN__none = 0,\n')
    for n in fnames:
        h.append('    TLN_%s = %d,\n' % (cname(n), fname_idx[n]))
    h.append('};\n')

    cc = []
    cc.append('/*\n * P4OS - Mensajes: the TL schema\'s tables, layer %d. GENERATED by\n'
              ' * tools/tl_gen.py from tools/schema/layer%d.tl: do not edit by hand.\n */\n' % (layer, layer))
    cc.append('#include "mj_tl.h"\n\n')
    cc.append('const tl_type_t tl_types[TL_NTYPES] = {\n')
    for k, a in types:
        cc.append('    {%s, %d},\n' % (k, a))
    cc.append('};\n\nconst tl_field_t tl_fields[TL_NFIELDS] = {\n')
    for n, ti, fi, bit in fields:
        cc.append('    {%d, %d, %d, %d},\n' % (n, ti, fi, bit))
    cc.append('};\n\nconst tl_ctor_t tl_ctors[TL_NCTORS] = {\n')
    first = 0
    for c in combs:
        cc.append('    {0x%08xu, %d, %d, %d, %d, %d}, /* %s */\n'
                  % (c.id, name_off[c.name], btype_idx.get(c.result, 0xffff) if not c.is_func else 0xffff,
                     first, len(c.fields), 1 if c.is_func else 0, c.name))
        first += len(c.fields)
    cc.append('};\n\n/* tl_ctors[] by id, for the reader */\nconst uint16_t tl_by_id[TL_NCTORS] = {\n')
    order = sorted(range(len(combs)), key=lambda i: combs[i].id)
    for i in range(0, len(order), 12):
        cc.append('    ' + ', '.join(str(x) for x in order[i:i + 12]) + ',\n')
    cc.append('};\n\n/* the field names, by TLN_ */\nconst uint32_t tl_fname_off[TL_NNAMES] = {\n    0,\n')
    for n in fnames:
        cc.append('    %d, /* %s */\n' % (name_off[n], n))
    cc.append('};\n\nconst char tl_names[%d] =\n' % (len(blob) + 1))
    # the blob as C string literals, a line at a time
    line = b''
    for b in blob:
        line += bytes([b])
        if b == 0 and len(line) > 60:
            cc.append('    "%s"\n' % line.decode().replace('\0', '\\0'))
            line = b''
    if line:
        cc.append('    "%s"\n' % line.decode().replace('\0', '\\0'))
    cc.append('    ;\n')

    with open(os.path.join(outdir, 'tl_schema.h'), 'w') as f:
        f.write(''.join(h))
    with open(os.path.join(outdir, 'tl_schema.c'), 'w') as f:
        f.write(''.join(cc))
    print('%d constructors, %d fields, %d types, %d names, %d bytes of names, layer %d'
          % (len(combs), len(fields), len(types), len(fnames), len(blob), layer), file=sys.stderr)


if __name__ == '__main__':
    main()
