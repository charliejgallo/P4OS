#!/usr/bin/env python3
"""
P4OS - Mensajes: the test vectors for tests/test_crypto.c.

    python3 vectors.py > vectors.h

Everything comes from the Python reference (tools/mtproto_ref.py, written
from core.telegram.org) or from the standards, never from the C under test:
SHA-1 and AES-256 from FIPS 180 and FIPS 197, the pq of the worked example
of core.telegram.org/mtproto/samples-auth_key, and the rest (IGE, msg_key,
RSA_PAD, the handshake's temporary key, SRP, PBKDF2, gzip, TL both ways)
computed from fixed random bytes.
"""
import gzip
import hashlib
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'tools'))
import mtproto_ref as R  # noqa: E402
import tl_schema  # noqa: E402

rnd = random.Random(20261127)


def rb(n):
    return bytes(rnd.getrandbits(8) for _ in range(n))


out = []


def arr(name, b):
    out.append('static const uint8_t %s[%d] = {' % (name, len(b)))
    for i in range(0, len(b), 16):
        out.append('    ' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',')
    out.append('};')


out.append('/* GENERATED by tests/vectors.py: do not edit. */')
out.append('#pragma once\n#include <stdint.h>\n')

# SHA-1, FIPS 180-1 "abc"
arr('V_SHA1_ABC', hashlib.sha1(b'abc').digest())

# AES-256, FIPS 197 C.3
arr('V_AES_KEY', bytes(range(32)))
arr('V_AES_PT', bytes.fromhex('00112233445566778899aabbccddeeff'))
arr('V_AES_CT', bytes.fromhex('8ea2b7ca516745bfeafc49904b496089'))

# IGE
k, iv, pt = rb(32), rb(32), rb(160)
arr('V_IGE_KEY', k)
arr('V_IGE_IV', iv)
arr('V_IGE_PT', pt)
arr('V_IGE_CT', R.ige_encrypt(pt, k, iv))

# msg_key and the sealed message, both directions
ak = rb(256)
plain = rb(96)
arr('V_AK', ak)
arr('V_AK_ID', R.auth_key_id(ak))
arr('V_SEAL_PT', plain)
arr('V_SEAL_C2S', R.seal(ak, plain, 0))
arr('V_SEAL_S2C', R.seal(ak, plain, 8))

# RSA_PAD with Telegram's key and fixed random parts
n_tg = int('e8bb3305c0b52c6cf2afdf7637313489e63e05268e5badb601af417786472e5f93b85438968e20e6729a301c0afc12'
           '1bf7151f834436f7fda680847a66bf64accec78ee21c0b316f0edafe2f41908da7bd1f4a5107638eeb67040ace472a'
           '14f90d9f7c2b7def99688ba3073adb5750bb02964902a359fe745d8170e36876d4fd8a5d41b2a76cbff9a13267eb95'
           '80b2d06d10357448d20d9da2191cb5d8c93982961cdfdeda629e37f1fb09a0722027696032fe61ed663db7a37f6f26'
           '3d370f69db53a0dc0a1748bdaaff6209d5645485e6e001d1953255757e4b8e42813347b11da6ab500fd0ace7e6dfa3'
           '736199ccaf9397ed0745a427dcfa6cd67bcb1acff3', 16)
data = rb(96)
pad = rb(192 - 96)
while True:
    tk = rb(32)
    try:
        enc = R.rsa_pad_encrypt(data, n_tg, 65537, temp_key=tk, padding=pad)
        break
    except ValueError:
        continue
arr('V_RSA_DATA', data)
arr('V_RSA_PAD', pad)
arr('V_RSA_TK', tk)
arr('V_RSA_N', n_tg.to_bytes(256, 'big'))
arr('V_RSA_ENC', enc)
out.append('#define V_RSA_FP 0x%016xull' % (R.rsa_fingerprint(n_tg, 65537) & (2**64 - 1)))

# the handshake's temporary AES key and the nonce hash
nn, sn = rb(32), rb(16)
tkey, tiv = R.tmp_aes(nn, sn)
arr('V_NEW_NONCE', nn)
arr('V_SERVER_NONCE', sn)
arr('V_TMP_KEY', tkey)
arr('V_TMP_IV', tiv)
arr('V_NNH1', R.new_nonce_hash(nn, ak, 1))

# DH: g^b mod p and (g^a)^b
b = rb(256)
ga = pow(3, int.from_bytes(rb(256), 'big'), R.DH_PRIME)
arr('V_DH_B', b)
arr('V_DH_GB', pow(3, int.from_bytes(b, 'big'), R.DH_PRIME).to_bytes(256, 'big'))
arr('V_DH_GA', ga.to_bytes(256, 'big'))
arr('V_DH_KEY', pow(ga, int.from_bytes(b, 'big'), R.DH_PRIME).to_bytes(256, 'big'))

# pq, core.telegram.org/mtproto/samples-auth_key
out.append('#define V_PQ 0x17ED48941A08F981ull\n#define V_P 0x494C553Bu\n#define V_Q 0x53911073u')

# PBKDF2-HMAC-SHA512, 1000 rounds (the test of the 100 000 is SRP's)
arr('V_PBKDF2', hashlib.pbkdf2_hmac('sha512', b'contrasenia', b'sal-de-prueba', 1000, 64))

# SRP
s1, s2 = rb(40), rb(16)
srp_b = int.from_bytes(rb(256), 'big')
srp_a = rb(256)
pw = 'pescado-y-papas'
v = R.srp_verifier(pw, s1, s2, 3, R.DH_PRIME)
B = R.srp_server_B(v, 3, R.DH_PRIME, srp_b)
A, M1 = R.srp_client(pw, s1, s2, 3, R.DH_PRIME, B, int.from_bytes(srp_a, 'big'))
assert R.srp_server_check(v, 3, R.DH_PRIME, srp_b, B, s1, s2, A, M1)
out.append('#define V_SRP_PASSWORD "%s"' % pw)
arr('V_SRP_SALT1', s1)
arr('V_SRP_SALT2', s2)
arr('V_SRP_B', B.to_bytes(256, 'big'))
arr('V_SRP_A_RAND', srp_a)
arr('V_SRP_A', A)
arr('V_SRP_M1', M1)

# gzip
text = ('Mensajes ' * 300).encode()
arr('V_GZ_IN', gzip.compress(text, 9, mtime=0))
out.append('#define V_GZ_OUT_LEN %d' % len(text))

# TL: a message the C reads, and a request the C must write the same
sch = tl_schema.Schema.load(os.path.join(HERE, '..', 'tools', 'schema', 'layer234.tl'))
codec = tl_schema.TLCodec(sch)
msg = {'_': 'message', 'out': True, 'id': 4321, 'peer_id': {'_': 'peerUser', 'user_id': 777000123456},
       'date': 1764240000, 'message': 'hola, ¿qué tal? 👋',
       'reply_to': {'_': 'messageReplyHeader', 'reply_to_msg_id': 4300},
       'entities': [{'_': 'messageEntityBold', 'offset': 0, 'length': 4}],
       'views': 12, 'forwards': 3}
arr('V_TL_MSG', codec.encode(msg))
req = {'_': 'messages.getHistory',
       'peer': {'_': 'inputPeerChannel', 'channel_id': 1234567890123, 'access_hash': -5555555555555},
       'offset_id': 0, 'offset_date': 0, 'add_offset': 0, 'limit': 40, 'max_id': 0, 'min_id': 0, 'hash': 0}
arr('V_TL_REQ', codec.encode(req))
send = {'_': 'messages.sendMessage', 'silent': True,
        'peer': {'_': 'inputPeerSelf'}, 'message': 'x' * 300, 'random_id': 99,
        'reply_to': {'_': 'inputReplyToMessage', 'reply_to_msg_id': 5}}
arr('V_TL_SEND', codec.encode(send))
gz = {'_': 'rpc_error', 'error_code': 420, 'error_message': 'FLOOD_WAIT_7'}
raw = codec.encode(gz)
packed = (0x3072cfa1).to_bytes(4, 'little') + tl_schema.write_bytes(gzip.compress(raw, mtime=0))
arr('V_TL_GZ', packed)

print('\n'.join(out))
