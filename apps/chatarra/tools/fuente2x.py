def comprobar():
    for c in range(32, 96):
        g = G[chr(c)]
        assert len(g) == 14, (chr(c), len(g))
        for r in g:
            assert len(r) == 10, (chr(c), r)


def escribir(path):
    comprobar()
    out = ['/* GENERATED by tools/fuente2x.py: the 10x14 font, one uint16_t per',
           ' * row, bit 9 the leftmost pixel, from \' \' (32) to \'_\' (95). */',
           'static const uint16_t ch_fuente2x[64][14] = {']
    for c in range(32, 96):
        filas = []
        for r in G[chr(c)]:
            v = 0
            for i, ch in enumerate(r):
                if ch == '#': v |= 1 << (9 - i)
            filas.append('0x%03X' % v)
        nombre = {'\\': 'backslash', "'": 'apostrophe'}.get(chr(c), chr(c))
        out.append('    { %s },   /* %s */' % (', '.join(filas), nombre))
    out.append('};')
    open(path, 'w').write('\n'.join(out) + '\n')


