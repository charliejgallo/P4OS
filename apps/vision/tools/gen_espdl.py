#!/usr/bin/env python3
"""P4OS - Vision: writes the five files esp-dl's CMake generates from
spec/*.yml, for a build of everything (DL_COMPILE_ALL):

    dl_compile_config.h, dl_kernel.inc, dl_conv_select.inc,
    dl_module_includes.inc, dl_module_register.inc

    gen_espdl.py <esp-dl dir> <out dir> p4|c

p4 is the board (the SIMD kernels, esp-dl's "pie_v2"); c the simulator
(esp-dl's plain C kernels). engine/gen/p4 and engine/gen/c are its output,
kept in git: run it again only when engine/espdl changes.

The YAML is read as data with a small parser of the subset those files use
(maps, lists, flow lists, scalars); nothing of esp-dl's own tooling runs.
"""
import sys
from pathlib import Path


def scalar(t):
    t = t.strip()
    if t.startswith('[') and t.endswith(']'):
        return [scalar(x) for x in t[1:-1].split(',') if x.strip()]
    if len(t) >= 2 and t[0] == t[-1] and t[0] in '"\'':
        return t[1:-1]
    if t in ('true', 'false'):
        return t == 'true'
    return t


def load(path):
    rows = []
    for line in path.read_text().splitlines():
        s = line.split(' #')[0].rstrip() if not line.lstrip().startswith('#') else ''
        if s.strip():
            rows.append((len(s) - len(s.lstrip()), s.strip()))
    pos = 0

    def block(ind):
        nonlocal pos
        out = None
        while pos < len(rows) and rows[pos][0] >= ind:
            i, s = rows[pos]
            if s.startswith('- '):
                out = out if out is not None else []
                body = s[2:]
                if ':' in body and not body.startswith('['):
                    # a map item: its first key is on the dash line
                    rows[pos] = (i + 2, body)
                    out.append(block(i + 2))
                else:
                    out.append(scalar(body))
                    pos += 1
            else:
                out = out if out is not None else {}
                k, v = s.split(':', 1)
                pos += 1
                if v.strip():
                    out[k.strip()] = scalar(v)
                elif pos < len(rows) and rows[pos][0] > i:
                    out[k.strip()] = block(rows[pos][0])
                else:
                    out[k.strip()] = {}
        return out

    return block(rows[0][0])


CONV_DTYPE = {'s8': 0, 's16': 1, 'w8a16': 2}
CONV_KSHAPE = {'11': 0, '33': 1, 'hw': 2}
CONV_ACT = {'linear': 0, 'relu': 1, 'leakyrelu': 2, 'prelu': 3}


def conv_key(r):
    # the same packing as dl_conv_pack_key() in dl_base_conv_select.cpp
    return (CONV_DTYPE[str(r['dtype'])] | ((1 if str(r['group']) == 'dw' else 0) << 2)
            | (CONV_KSHAPE[str(r['kshape'])] << 3) | ((1 if r.get('bias') else 0) << 5)
            | (CONV_ACT[str(r['act'])] << 6) | ((1 if r.get('per_ch') else 0) << 8)
            | ((1 if r.get('c_align') else 0) << 9))


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    target = {'p4': 'pie_v2', 'c': 'c'}[sys.argv[3]]
    prefix = {'pie_v2': 'dl_esp32p4_', 'c': 'dl_c_'}[target]
    out.mkdir(parents=True, exist_ok=True)
    ops = load(src / 'spec/ops.yml')
    kernels = load(src / 'spec/kernels.yml')
    conv = load(src / 'spec/select/Conv.yml')
    gen = '/* Generated by gen_espdl.py from esp-dl spec/*.yml. */\n'

    (out / 'dl_compile_config.h').write_text(gen + '#pragma once\n\n#define DL_COMPILE_ALL 1\n')

    lines = [gen]
    for n in sorted(k for k in kernels['symbols'] if k.startswith(prefix)):
        lines.append('    {"%s", (dl_kernel_erased_t)(%s)},\n' % (n, n))
    (out / 'dl_kernel.inc').write_text(''.join(lines))

    slots = conv['slots'][target]
    rows = {}
    for r in conv['rules']:
        if r.get('target') != target:
            continue
        vals = [r.get(s) or None for s in slots] + [None] * (3 - len(slots))
        k = conv_key(r)
        if k in rows and rows[k] != vals:
            sys.exit('Conv.yml: key 0x%04x twice with different kernels' % k)
        rows[k] = vals
    lines = [gen]
    for k in sorted(rows):
        lines.append('    {0x%04x, %s},\n' % (k, ', '.join('"%s"' % v if v else 'nullptr' for v in rows[k])))
    (out / 'dl_conv_select.inc').write_text(''.join(lines))

    mods = sorted((op, s['module']['header'], s['module']['class'])
                  for op, s in ops['ops'].items() if isinstance(s, dict) and isinstance(s.get('module'), dict))
    (out / 'dl_module_includes.inc').write_text(gen + ''.join('#include "%s"\n' % h for _, h, _ in mods))
    (out / 'dl_module_register.inc').write_text(
        gen + ''.join('register_module("%s", %s::deserialize);\n' % (op, c) for op, _, c in mods))
    print('%d conv rows, %d modules' % (len(rows), len(mods)))


main()
