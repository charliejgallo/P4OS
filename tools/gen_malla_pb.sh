#!/bin/bash
# Regenerates the protobuf code of the Malla app (apps/malla, a Meshtastic
# client) from Meshtastic's .proto files, with nanopb.
#
#   tools/gen_malla_pb.sh                      # clones the pinned tags below
#   tools/gen_malla_pb.sh <protobufs> <nanopb> # or uses checkouts you have
#
# What it writes, all of it kept in git:
#   apps/malla/proto/meshtastic/*.proto,.options   the sources (GPL-3.0)
#   apps/malla/main/pb/pb*.{c,h}                   nanopb's runtime (zlib)
#   apps/malla/main/pb/meshtastic/*.pb.{c,h}       the generated code
#
# The generator needs Python with protobuf and grpcio-tools; when the
# python3 on the PATH lacks them, a virtual environment is made in the
# temporary directory and thrown away at the end.
set -euo pipefail

PROTO_TAG=v2.8.0            # Meshtastic's protobufs, as firmware 2.8.0 carries them
NANOPB_TAG=nanopb-0.4.9.1   # the nanopb Meshtastic's firmware builds with

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="$ROOT/apps/malla"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

PROTOS="${1:-}"
NANOPB="${2:-}"
if [ -z "$PROTOS" ]; then
    git clone -q --depth 1 --branch "$PROTO_TAG" https://github.com/meshtastic/protobufs.git "$TMP/protobufs"
    PROTOS="$TMP/protobufs"
fi
if [ -z "$NANOPB" ]; then
    git clone -q --depth 1 --branch "$NANOPB_TAG" https://github.com/nanopb/nanopb.git "$TMP/nanopb"
    NANOPB="$TMP/nanopb"
fi

PY=python3
if ! $PY -c 'import google.protobuf, grpc_tools' 2>/dev/null; then
    python3 -m venv "$TMP/venv"
    "$TMP/venv/bin/pip" -q install protobuf grpcio-tools
    PY="$TMP/venv/bin/python"
fi

# Only what a client needs: the radio's API (mesh), what it carries
# (config, channels, modules, telemetry, admin), the URL of a channel set
# (apponly) and what those import.
FILES="mesh channel config module_config portnums telemetry xmodem device_ui admin connection_status apponly atak"

rm -rf "$APP/main/pb" "$APP/proto"
mkdir -p "$APP/main/pb/meshtastic" "$APP/proto/meshtastic"
args=()
for f in $FILES; do
    cp "$PROTOS/meshtastic/$f.proto" "$APP/proto/meshtastic/"
    [ -f "$PROTOS/meshtastic/$f.options" ] && cp "$PROTOS/meshtastic/$f.options" "$APP/proto/meshtastic/"
    args+=("meshtastic/$f.proto")
done
cp "$PROTOS/LICENSE" "$APP/proto/LICENSE"
cp "$PROTOS/nanopb.proto" "$APP/proto/" 2>/dev/null || true

(cd "$PROTOS" && "$PY" "$NANOPB/generator/nanopb_generator.py" -q -I . -D "$APP/main/pb" "${args[@]}")

for f in pb.h pb_common.c pb_common.h pb_decode.c pb_decode.h pb_encode.c pb_encode.h; do
    cp "$NANOPB/$f" "$APP/main/pb/"
done
cp "$NANOPB/LICENSE.txt" "$APP/main/pb/LICENSE-nanopb.txt"

# The names of the hardware models, for the node list ("HELTEC_V3" -> "Heltec V3"
# is the app's business; here they go as the enum spells them).
python3 - "$APP/main/pb/meshtastic/mesh.pb.h" "$APP/main/pb/msh_hw_names.c" <<'PYEOF'
import re, sys
src = open(sys.argv[1]).read()
body = re.search(r'typedef enum _meshtastic_HardwareModel \{(.*?)\} meshtastic_HardwareModel;', src, re.S).group(1)
items = re.findall(r'meshtastic_HardwareModel_(\w+) = (\d+)', body)
with open(sys.argv[2], 'w') as f:
    f.write('/* Generated by tools/gen_malla_pb.sh from meshtastic/mesh.proto (GPL-3.0). */\n')
    f.write('#include <stddef.h>\n\n')
    f.write('static const struct { int v; const char *name; } HW[] = {\n')
    for name, v in items:
        f.write('    { %s, "%s" },\n' % (v, name))
    f.write('};\n\n')
    f.write('const char *msh_hw_name(int model)\n{\n')
    f.write('    for (size_t i = 0; i < sizeof HW / sizeof HW[0]; i++)\n')
    f.write('        if (HW[i].v == model) return HW[i].name;\n')
    f.write('    return NULL;\n}\n')
PYEOF

{
    echo "Generated by tools/gen_malla_pb.sh on $(date -u +%Y-%m-%d)"
    echo "meshtastic/protobufs $PROTO_TAG ($(git -C "$PROTOS" rev-parse --short HEAD 2>/dev/null || echo '?'))"
    echo "nanopb $NANOPB_TAG ($(git -C "$NANOPB" rev-parse --short HEAD 2>/dev/null || echo '?'))"
} > "$APP/main/pb/VERSION.txt"

echo "malla: $(ls "$APP/main/pb/meshtastic" | wc -l | tr -d ' ') generated files in apps/malla/main/pb"
