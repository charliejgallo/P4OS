/* Set when one of the loader's allocations comes back empty: the dlopen
 * that follows failed for memory, not for a broken .so, and is worth
 * another try once memory is back (the scan, dyn_create). */
static bool s_oom;

static void *elf_malloc(uint32_t n, bool exec);

void *__wrap_esp_elf_malloc(uint32_t n, bool exec)
{
    void *p = elf_malloc(n, exec);
    if (!p) s_oom = true;
    return p;
}

static void *elf_malloc(uint32_t n, bool exec)
{
#if CONFIG_ELF_LOADER_TEXT_PSRAM_MMU
    /* RAM audit prototype: the code goes to PSRAM, 64 KB-aligned so that the
     * loader maps whole instruction-bus pages at it (esp_elf_esp32s3.c). The
     * internal reservation is not used at all. */
    if (exec) {
        void *p = heap_caps_aligned_alloc(0x10000, n, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
        if (!p) {
            ESP_LOGE(TAG, "%u B of code: no PSRAM block", (unsigned)n);
        }
        return p;
    }
#elif AOS_CODE_IN_PSRAM
    /* ESP32-P4: the code in PSRAM on its own cache lines (128 B, L2), so
     * that writing it back and invalidating it never touches anyone else's
     * data. */
    if (exec) {
        void *p = heap_caps_aligned_alloc(128, (n + 127u) & ~127u, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
        if (!p) {
            ESP_LOGE(TAG, "%u B of code: no PSRAM block", (unsigned)n);
        }
        return p;
    }
#endif
    if (exec) {
        void *p = pool_alloc(n);
        if (p) {
            return p;
        }
        /* Falling back to the general heap is not free: it is going back to
         * the scenario the reservation came to solve, and there a large app
         * fits or does not depending on how the fragmentation turned out. Let
         * it show in the log. */
        ESP_LOGW(TAG, "%u B of code did NOT fit in the reservation: going to the "
                      "general heap (free %u B, largest block %u B). If this "
                      "comes up often, the reservation is too small.",
                 (unsigned)n,
                 (unsigned)heap_caps_get_free_size(MALLOC_CAP_EXEC),
                 (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_EXEC));
        return heap_caps_malloc(n, MALLOC_CAP_EXEC);
    }
    void *p = heap_caps_malloc(n, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    return p ? p : heap_caps_malloc(n, MALLOC_CAP_8BIT);
}

/* The free has to be intercepted TOO: otherwise the loader would hand free() a
 * pointer that never came out of the heap. */
void __wrap_esp_elf_free(void *ptr)
{
    if (!ptr || pool_free(ptr)) {
        return;
    }
    heap_caps_free(ptr);
}


/* --------------------------------------------------------------------------
 * Symbol lookup
 *
 * Every undefined symbol of a .so is looked up here while it loads, at boot
 * for every module and again each time an app opens. The table has ~2,800
 * entries and was walked with strcmp from the top: a libc symbol like memcpy
 * -which is not in it- cost the whole walk before the loader's own table
 * even got asked. So the first scan sorts an index of pointers into it (in
 * PSRAM, ~11 KB) and the lookup is a binary search, a dozen comparisons.
 * Among duplicate names the first in the table still wins, as before.
 * -------------------------------------------------------------------------- */

static const struct esp_elfsym **s_sym_index;
static int      s_sym_count;
static int64_t  s_resolve_us;
static uint32_t s_resolve_calls;

static int sym_cmp(const void *a, const void *b)
{
    const struct esp_elfsym *x = *(const struct esp_elfsym *const *)a;
    const struct esp_elfsym *y = *(const struct esp_elfsym *const *)b;
    int c = strcmp(x->name, y->name);
    if (c) {
        return c;
    }
    return (x < y) ? -1 : (x > y);      /* the table's order among equals */
}

static void sym_index_build(void)
{
    if (s_sym_index) {
        return;
    }
    int n = 0;
    while (aos_symbol_table[n].name) {
        n++;
    }
    s_sym_index = heap_caps_malloc(sizeof(*s_sym_index) * (size_t)n,
                                   MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!s_sym_index) {
        return;                         /* the linear walk still works */
    }
    for (int i = 0; i < n; i++) {
        s_sym_index[i] = &aos_symbol_table[i];
    }
    qsort(s_sym_index, (size_t)n, sizeof(*s_sym_index), sym_cmp);
    s_sym_count = n;
}

static uintptr_t lookup_own(const char *name)
{
    if (!s_sym_index) {
        for (const struct esp_elfsym *sym = aos_symbol_table; sym->name; sym++) {
            if (strcmp(sym->name, name) == 0) {
                return (uintptr_t)sym->sym;
            }
        }
        return 0;
    }
    int lo = 0, hi = s_sym_count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        int c = strcmp(s_sym_index[mid]->name, name);
        if (c == 0) {
            while (mid > 0 && strcmp(s_sym_index[mid - 1]->name, name) == 0) {
                mid--;
            }
            return (uintptr_t)s_sym_index[mid]->sym;
        }
        if (c < 0) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return 0;
}

static uintptr_t resolver(const char *name)
{
    int64_t t = esp_timer_get_time();
    uintptr_t addr = lookup_own(name);
    if (!addr) {
        addr = elf_find_sym_default(name);
    }
    s_resolve_us += esp_timer_get_time() - t;
    s_resolve_calls++;
    return addr;
}

static dynapp_t *find_by_id(const char *id)
{
    for (int i = 0; i < s_count; i++) {
        if (s_apps[i].in_use && strcmp(s_apps[i].id, id) == 0) {
            return &s_apps[i];
        }
    }
    return NULL;
}

bool aos_dynapp_is_dynamic(const char *app_id)
{
    return app_id && find_by_id(app_id);
}

/* --------------------------------------------------------------------------
 * Opening and closing the .so
 * -------------------------------------------------------------------------- */

/* Opens the module and returns the aos_app_t its init() builds. */
/* The loader's dlopen() hands back the SAME module when it is already
 * loaded, with no count (elf_loader's dlmod_insert), and dlclose() unloads it
 * outright. A module with several apps (lua.so, python.so) is shared that
 * way: closing one of them took the code from under the other (seen on the
 * board going from one Python app to another: illegal instruction, pc == ra).
 * So every dlclose goes through here: the module is only unloaded when no
 * live app holds it (a handle not about to be closed), and then every entry
 * that pointed at it lets go. 'self' is the entry closing, or NULL.
 * Returns whether it was unloaded. */
static bool module_release(void *handle, dynapp_t *self)
{
    if (!handle) {
        return false;
    }
    for (int i = 0; i < s_count; i++) {
        dynapp_t *a = &s_apps[i];
        if (a != self && a->in_use && a->handle == handle && !a->pending_close) {
            ESP_LOGI(TAG, "%s stays loaded: %s still uses it", a->file, a->id);
            return false;
        }
    }
    dlclose(handle);
    for (int i = 0; i < s_count; i++) {
        dynapp_t *a = &s_apps[i];
        if (a != self && a->handle == handle) {
            a->handle = NULL;
            a->pending_close = false;
            memset(&a->loaded, 0, sizeof(a->loaded));
        }
    }
    return true;
}

#if AOS_CODE_IN_PSRAM
/* The big blocks of the PSRAM heap in address order, used and free, for
 * seeing what splits it (2026-11-08: 14 MB free and the largest block 9.4
 * MB, and a 5.5 MB app that did not fit). Collected under the heap's lock
 * into a buffer taken before, printed after. */
typedef struct { uint32_t off, size; bool used; } pblk_t;
typedef struct { pblk_t *b; int n, max; uintptr_t base; } pwalk_t;

static bool pwalk_cb(walker_heap_into_t heap, walker_block_info_t blk, void *user)
{
    pwalk_t *w = user;
    if (!w->base) w->base = (uintptr_t)heap.start;
    bool big = blk.used ? blk.size >= 256 * 1024 : blk.size >= 512 * 1024;
    if (big && w->n < w->max) {
        w->b[w->n].off = (uint32_t)((uintptr_t)blk.ptr - w->base);
        w->b[w->n].size = (uint32_t)blk.size;
        w->b[w->n].used = blk.used;
        w->n++;
    }
    return true;
}

static void psram_map_log(void)
{
    pwalk_t w = { .max = 48 };
    w.b = heap_caps_malloc(w.max * sizeof *w.b, MALLOC_CAP_SPIRAM);
    if (!w.b) return;
    heap_caps_walk(MALLOC_CAP_SPIRAM, pwalk_cb, &w);
    ESP_LOGW(TAG, "PSRAM blocks of 256 KB used or 512 KB free and up, by address:");
    for (int i = 0; i < w.n; i++)
        ESP_LOGW(TAG, "  +%5u KB  %5u KB  %s", (unsigned)(w.b[i].off / 1024), (unsigned)(w.b[i].size / 1024),
                 w.b[i].used ? "used" : "free");
    free(w.b);
}
#endif

static bool module_open(const char *filename, uint32_t index,
                        void **out_handle, aos_app_t *out_app)
{
    char relative[160];
    snprintf(relative, sizeof(relative), "/%s/%s", AOS_DYNAPP_RELATIVE, filename);

    /* Size and date of the file: without this there is no way to know whether
     * the SD has the freshly compiled .so or an old one, and every subsequent
     * diagnosis is left hanging. It happens more often than it seems. */
    {
        char full[192];
        snprintf(full, sizeof(full), "%s%s", CONFIG_BSP_SD_MOUNT_POINT, relative);
        struct stat st;
        if (stat(full, &st) == 0) {
            struct tm tm_buf;
            char cuando[24] = "?";
            localtime_r(&st.st_mtime, &tm_buf);
            strftime(cuando, sizeof(cuando), "%Y-%m-%d %H:%M", &tm_buf);
            ESP_LOGI(TAG, "  %s: %u bytes, modified %s",
                     filename, (unsigned)st.st_size, cuando);
        } else {
            ESP_LOGW(TAG, "  %s: could not read the size (%s)", filename, full);
        }
    }

#if AOS_CODE_IN_PSRAM
    /* the code goes to PSRAM: that is the memory to look at. A .so needs
     * about twice its size at once (the file read whole, then the image). */
    ESP_LOGI(TAG, "opening %s | PSRAM: free %u KB, largest block %u KB",
             filename,
             (unsigned)(heap_caps_get_free_size(MALLOC_CAP_SPIRAM) / 1024),
             (unsigned)(heap_caps_get_largest_free_block(MALLOC_CAP_SPIRAM) / 1024));
#else
    ESP_LOGI(TAG, "opening %s | executable: free %u B, largest block %u B | "
                  "internal: free %u B, largest block %u B",
             filename,
             (unsigned)heap_caps_get_free_size(MALLOC_CAP_EXEC),
             (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_EXEC),
             (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL),
             (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL));
#endif

    s_oom = false;
    void *handle = dlopen(relative, RTLD_NOW);
    if (!handle) {
        ESP_LOGE(TAG, "dlopen(%s) failed: %s%s", relative, dlerror(), s_oom ? " (out of memory)" : "");
#if AOS_CODE_IN_PSRAM
        ESP_LOGW(TAG, "PSRAM after the failure: free %u KB, largest block %u KB",
                 (unsigned)(heap_caps_get_free_size(MALLOC_CAP_SPIRAM) / 1024),
                 (unsigned)(heap_caps_get_largest_free_block(MALLOC_CAP_SPIRAM) / 1024));
        if (s_oom) psram_map_log();
#else
        /* The map of the executable heap: it distinguishes "there is no
         * memory" from "there is, but in pieces". With 54 KB free and the
         * largest hole at 36 KB, a 45 KB app does not fit even though the
         * total is there. */
        ESP_LOGW(TAG, "--- blocks of the executable heap ---");
        heap_caps_dump(MALLOC_CAP_EXEC);
#endif
        return false;
    }

    /* Espressif's loader only indexes symbols of function type, which is why
     * the entry point is two functions and not a structure (see aos_app.h). */
    uint32_t (*abi_fn)(void)            = dlsym(handle, "aos_app_abi");
    bool     (*init_fn)(aos_app_t *app) = dlsym(handle, "aos_app_init");

    /* Optional, and only lua.so has them today: a module that brings several
     * apps (see aos_app.h). Without them the module has exactly one, which is
     * what every other .so on the card is. */
    bool (*init_at_fn)(aos_app_t *app, uint32_t index) =
        dlsym(handle, "aos_app_init_at");

    if (!abi_fn || !init_fn) {
        ESP_LOGE(TAG, "%s does not export aos_app_abi/aos_app_init", filename);
        module_release(handle, NULL);
        return false;
    }

    uint32_t abi = abi_fn();
    if (abi != AOS_ABI_VERSION) {
        ESP_LOGE(TAG, "%s uses ABI %u and the firmware expects %u: rebuild it",
                 filename, (unsigned)abi, (unsigned)AOS_ABI_VERSION);
        module_release(handle, NULL);
        return false;
    }

    memset(out_app, 0, sizeof(*out_app));
    bool ok = init_at_fn ? init_at_fn(out_app, index) : (index == 0 && init_fn(out_app));
    if (!ok) {
        ESP_LOGE(TAG, "%s failed to initialise app %u", filename, (unsigned)index);
        module_release(handle, NULL);
        return false;
    }

    *out_handle = handle;
    return true;
}


static void module_close(dynapp_t *app);

/* Second attempt when there is no executable memory.
 *
 * Two levels, and deliberately NEITHER evicts an active background app: if the
 * Recorder is recording, unloading it stops the recording without warning.
 * Failing with a message saying who is holding the memory is preferred.
 *
 *   1. Drain the pending closes. dyn_destroy() only marks; the real close
 *      happens on the next aos_dynapp_tick(). If the load is attempted before
 *      that tick, it fails with the memory one step away.
 *   2. Unload modules that were left loaded without being in use or being
 *      background ones. There should not be any; if one turns up, it is a bug
 *      and this papers over it -but leaves it noted in the log-. */
static bool liberar_ejecutable(const dynapp_t *excepto)
{
    bool libero = false;

    for (int i = 0; i < s_count; i++) {
        dynapp_t *a = &s_apps[i];
        if (!a->in_use || &s_apps[i] == excepto || !a->handle) {
            continue;
        }
        if (a->pending_close) {
            ESP_LOGW(TAG, "out of memory: closing %s early", a->file);
            a->pending_close = false;
            module_close(a);
            libero = true;
        }
    }
    return libero;
}

/* Who is holding memory, so we can tell the user. */
static const char *retenedor(void)
{
    for (int i = 0; i < s_count; i++) {
        if (s_apps[i].in_use && s_apps[i].handle) {
            return s_apps[i].name[0] ? s_apps[i].name : s_apps[i].file;
        }
    }
    return NULL;
}

static bool module_ensure_open(dynapp_t *app)
{
    if (app->handle) {
        app->pending_close = false;     /* it was reopened before being closed */
        return true;
    }
    if (module_open(app->file, app->index, &app->handle, &app->loaded)) {
        return true;
    }

    /* One retry, after recovering whatever can be recovered without breaking
     * anything. On the P4 the memory is PSRAM, and what holds it is mostly
     * the apps hidden in the background and the wallpaper photos: those go
     * (aos_ui_make_room), the hidden apps' modules with them. Called from
     * create(), with the UI's lock. */
    bool freed = false;
    if (s_oom && aos_ui_make_room() > 0) freed = true;
    if (liberar_ejecutable(app)) freed = true;
    if (freed && module_open(app->file, app->index, &app->handle, &app->loaded)) {
        ESP_LOGI(TAG, "%s loaded on the second attempt", app->file);
        return true;
    }
    return false;
}

static void module_close(dynapp_t *app)
{
    if (!app->handle) {
        ESP_LOGW(TAG, "closing %s with no handle: was it already unloaded?", app->file);
        return;
    }
    void *handle = app->handle;
    app->handle = NULL;
    memset(&app->loaded, 0, sizeof(app->loaded));
    if (!module_release(handle, app)) {
        return;
    }
    ESP_LOGI(TAG, "%s unloaded (executable free: %u B)", app->file,
             (unsigned)heap_caps_get_free_size(MALLOC_CAP_EXEC));
}

