/*
 * AmoledOS - Dynamic loading of applications.
 *
 * Apps are loaded **on demand**: at startup each .so is only opened far enough
 * to read its descriptor (name, icon, colour) and closed again. The code
 * enters RAM only when the user opens the app, and leaves when they close it.
 *
 * This is not an optimisation, it is the only thing that fits. The apps' .text
 * has to live in executable internal RAM, of which there is about 83 KB; the
 * six apps together add up to 134 KB. One at a time, on the other hand, is
 * plenty: the largest is 43 KB. Measured on the board.
 */
