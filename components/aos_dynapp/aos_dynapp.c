/* Where a scan's time goes, logged at its end (docs/APPS-P4.md, "Measured"). */
static struct {
    int64_t open_us;        /* dlopen + the probe's init() */
    int64_t lock_us;        /* waiting for the UI's lock */
    int64_t reg_us;         /* aos_ui_register_app itself */
} s_scan_cost;

/* Registers apps of one module, from index 'from' to the end, or only the
 * first when first_only. Returns how many were registered and, in *total,
 * how many the module declares.
 *
 * The UI's lock is taken once per batch and not once per app: at boot the
 * UI task is drawing, and every separate lock is a wait for its frame to
 * end. A module with many apps (lua.so) paid that wait once per script. */
#define REGISTER_BATCH  16

/* One app into the launcher: our own copies of its strings, the trampolines,
 * and the icon when it comes from the cache (from the .so, init() already
 * handed it over). The UI's lock is held across calls (*locked) and let go
 * every REGISTER_BATCH apps for a frame. */
static bool register_one(const char *filename, uint16_t index, const aos_app_desc_t *d,
                         const uint8_t *aic, size_t aic_len, bool *locked, int *in_batch)
{
    if (s_count >= MAX_DYNAPPS) {
        ESP_LOGE(TAG, "%s app %u does not fit: the limit is %d", filename, (unsigned)index, MAX_DYNAPPS);
        return false;
    }
    dynapp_t *slot = &s_apps[s_count];
    memset(slot, 0, sizeof(*slot));
    snprintf(slot->file, sizeof(slot->file), "%s", filename);
    snprintf(slot->id,   sizeof(slot->id),   "%s", d->id   ? d->id   : filename);
    snprintf(slot->name, sizeof(slot->name), "%s", d->name ? d->name : filename);
    snprintf(slot->icon, sizeof(slot->icon), "%s", d->icon ? d->icon : "");
    slot->index = index;

    aos_app_t stub = {0};
    stub.desc = *d;
    stub.desc.id   = slot->id;      /* pointing at OUR copies */
    stub.desc.name = slot->name;
    stub.desc.icon = slot->icon[0] ? slot->icon : NULL;

    stub.create  = dyn_create;
    stub.destroy = dyn_destroy;
    stub.show    = dyn_show;
    stub.hide    = dyn_hide;
    stub.back    = dyn_back;
    stub.button  = dyn_button;
    stub.resize  = dyn_resize;
    stub.tick    = dyn_tick;
    if (aic && aic_len) aos_icon_set_ops(&stub, aic, aic_len);

    slot->in_use = true;
    s_count++;

    int64_t t;
    if (!*locked) {
        t = esp_timer_get_time();
        *locked = aos_hal_lock(1000);
        s_scan_cost.lock_us += esp_timer_get_time() - t;
    }
    bool ok = false;
    if (*locked) {
        t = esp_timer_get_time();
        ok = aos_ui_register_app(&stub);
        s_scan_cost.reg_us += esp_timer_get_time() - t;
        if (++*in_batch >= REGISTER_BATCH) {
            aos_hal_unlock();       /* let a frame through */
            *locked = false;
            *in_batch = 0;
        }
    }
    if (!ok) {
        /* aos_ui_register_app says why in its own log line; this one
         * names the file, which is what tells you which .so to look at. */
        ESP_LOGE(TAG, "%s[%u] -> %s was refused by the launcher", filename, (unsigned)index, slot->id);
        slot->in_use = false;
        s_count--;
        return false;
    }
    ESP_LOGD(TAG, "registered %s[%u] -> %s (%s)", filename, (unsigned)index, slot->id, slot->name);
    return true;
}

static int register_apps(const char *filename, bool first_only, uint32_t *total)
{
    *total = 0;
    if (s_count >= MAX_DYNAPPS) {
        ESP_LOGE(TAG, "%s does not fit: the limit is %d dynamic apps and there are "
                      "already %d. Raise MAX_DYNAPPS or take a .so off the card",
                 filename, MAX_DYNAPPS, s_count);
        return 0;
    }

    int64_t t = esp_timer_get_time();
    void *handle = NULL;
    aos_app_t probe;
    if (!module_open(filename, 0, &handle, &probe)) {
        return 0;
    }
    s_scan_cost.open_us += esp_timer_get_time() - t;

    /* How many apps this module brings. Only lua.so answers; for everything
     * else the symbol is absent and the answer is one. The module stays open
     * for the whole loop: the alternative is a dlopen per app, and lua.so is
     * 144 KB. */
    uint32_t (*count_fn)(void) = dlsym(handle, "aos_app_count");
    bool (*init_at_fn)(aos_app_t *app, uint32_t index) =
        dlsym(handle, "aos_app_init_at");
    uint32_t n = (count_fn && init_at_fn) ? count_fn() : 1;
    if (n < 1) {
        n = 1;
    }
    *total = n;

    uint32_t from = first_only ? 0 : 1;
    uint32_t to   = first_only ? 1 : n;
    int registered = 0;
    bool locked = false;
    int in_batch = 0;

    for (uint32_t i = from; i < to; i++) {
        if (s_count >= MAX_DYNAPPS) {
            ESP_LOGE(TAG, "%s app %u does not fit: the limit is %d",
                     filename, (unsigned)i, MAX_DYNAPPS);
            break;
        }
        if (i > 0) {
            memset(&probe, 0, sizeof(probe));
            if (!init_at_fn(&probe, i)) {
                ESP_LOGE(TAG, "%s failed to describe app %u", filename, (unsigned)i);
                continue;
            }
        }

        if (!register_one(filename, (uint16_t)i, &probe.desc, NULL, 0, &locked, &in_batch)) continue;
        registered++;
    }
    if (locked) {
        aos_hal_unlock();
    }
    if (registered) {
        ESP_LOGI(TAG, "registered %s: %d app%s%s", filename, registered,
                 registered == 1 ? "" : "s", first_only && n > 1 ? " (more later)" : "");
    }

    /* descriptors read, the code goes away: it comes back in when it is opened
     * (unless one of its apps is open: a later scan of lua.so, say) */
    module_release(handle, NULL);
    return registered;
}

bool aos_dynapp_load(const char *filename)
{
    if (!filename) {
        return false;
    }
    /* One module arriving after boot: all of its apps, in the same two steps
     * as the scan. */
    uint32_t total = 0;
    if (register_apps(filename, true, &total) == 0) {
        return false;
    }
    if (total > 1) {
        register_apps(filename, false, &total);
    }
    return true;
}

/* --------------------------------------------------------------------------
 * Modules an app loads itself (aos_hal.h: aos_hal_module_open)
 *
 * An emulator's cores, one .so per console in the card's apps/<app>/: only
 * the one playing in memory, each with its licence, and a console added
 * without rebuilding the app. The same loader and resolver as the apps (the
 * firmware's table, the code in PSRAM), apart from the apps' own count
 * (module_release): the app opens and closes them.
 *
 * The loader keys its modules by the file's name without ".so": a core
 * named as a card app would be handed that app's module. Refused here.
 * -------------------------------------------------------------------------- */
struct aos_module {
    void *handle;
    char  name[48];
};

aos_module_t *aos_hal_module_open(const char *path, char *err, size_t errlen)
{
    if (err && errlen) err[0] = 0;
    if (!path || !*path) {
        if (err) snprintf(err, errlen, "%s", _("sin ruta"));
        return NULL;
    }
    /* the loader wants it from the card's root: "/apps/emulador/gba.so" */
    const char *rel = path;
    size_t mp = strlen(CONFIG_BSP_SD_MOUNT_POINT);
    if (!strncmp(rel, CONFIG_BSP_SD_MOUNT_POINT, mp) && rel[mp] == '/') rel += mp;
    const char *base = strrchr(rel, '/');
    base = base ? base + 1 : rel;
    size_t blen = strlen(base);
    if (blen < 4 || strcmp(base + blen - 3, ".so")) {
        if (err) snprintf(err, errlen, _("%s no es un .so"), base);
        return NULL;
    }
    for (int i = 0; i < s_count; i++) {
        if (s_apps[i].in_use && !strcmp(s_apps[i].file, base)) {
            if (err) snprintf(err, errlen, _("%s se llama como una app de la tarjeta: renombralo"), base);
            return NULL;
        }
    }
    aos_module_t *m = heap_caps_calloc(1, sizeof *m, MALLOC_CAP_SPIRAM);
    if (!m) {
        if (err) snprintf(err, errlen, "%s", _("sin memoria"));
        return NULL;
    }
    snprintf(m->name, sizeof m->name, "%.*s", (int)(blen - 3), base);
    char full[160];
    snprintf(full, sizeof full, "%s%s", rel[0] == '/' ? "" : "/", rel);
    m->handle = dlopen(full, RTLD_NOW);
    if (!m->handle) {
        if (err) snprintf(err, errlen, _("no se pudo cargar %s: %s"), base, dlerror());
        free(m);
        return NULL;
    }
    ESP_LOGI(TAG, "module %s opened by an app (%s)", m->name, full);
    return m;
}

void *aos_hal_module_sym(aos_module_t *m, const char *name)
{
    return m && m->handle && name ? dlsym(m->handle, name) : NULL;
}

void aos_hal_module_close(aos_module_t *m)
{
    if (!m) return;
    if (m->handle) {
        dlclose(m->handle);
        ESP_LOGI(TAG, "module %s closed (executable free: %u B)", m->name,
                 (unsigned)heap_caps_get_free_size(MALLOC_CAP_EXEC));
    }
    free(m);
}

bool aos_dynapp_unload(const char *app_id)
{
    dynapp_t *app = find_by_id(app_id);
    if (!app) {
        return false;
    }

    bool ok = false;
    if (aos_hal_lock(1000)) {
        ok = aos_ui_unregister_app(app_id);
        aos_hal_unlock();
    }
    if (ok) {
        module_close(app);
        app->in_use = false;
    }
    return ok;
}


/* Which modules are still loaded and how much executable memory they hold.
 *
 * An app with AOS_APP_FLAG_BACKGROUND is not destroyed on exit, so its .so
 * stays loaded until a restart. That is deliberate (the recorder has to go on
 * recording) but it is paid for in memory: PSRAM and MMU pages now, and until
 * v0.3.3 the internal reservation the code of ALL dynamic apps came from.
 * Without this list there is no way to know who is holding it. */
int aos_dynapp_loaded_list(char *out, size_t len)
{
    int n = 0;
    size_t used = 0;
    if (out && len) {
        out[0] = 0;
    }
    for (int i = 0; i < s_count; i++) {
        if (!s_apps[i].in_use || !s_apps[i].handle) {
            continue;
        }
        n++;
        if (out && used + 2 < len) {
            used += (size_t)snprintf(out + used, len - used, "%s%s",
                                     used ? " " : "", s_apps[i].file);
        }
    }
    return n;
}

void aos_dynapp_tick(void)
{
    for (int i = 0; i < s_count; i++) {
        if (s_apps[i].in_use && s_apps[i].pending_close) {
            s_apps[i].pending_close = false;
            module_close(&s_apps[i]);
        }
    }
}

static bool ends_with_so(const char *name)
{
    size_t len = strlen(name);
    return len > 3 && strcmp(name + len - 3, ".so") == 0;
}

/* --------------------------------------------------------------------------
 * The cache of the card's apps (2026-10-12)
 *
 * The scan used to dlopen() every .so only to read its descriptor: the whole
 * file read into PSRAM and relocated, init() called, closed again. With CAS
 * (5 MB, Giac inside) that one file cost 0.6-0.8 s of boot and a peak of
 * ~12 MB of PSRAM, and the small ones ~20 ms each. What init() leaves -the
 * descriptor and the icon it hands over (the apps' init does nothing else,
 * checked 2026-10-12)- goes into /data/apps.cache, and a .so whose name,
 * size and date match is registered from there without being opened. The
 * code is loaded when the app is opened, as before. Not cached: a module
 * with several apps (lua.so), whose list depends on the scripts on the card
 * and not on the .so. The whole cache belongs to one firmware (its ELF sha):
 * after an update every .so is opened once again.
 * -------------------------------------------------------------------------- */
#define CACHE_MAGIC     0x43505041u         /* "APPC" */
#define CACHE_VERSION   1
#define CACHE_AIC_MAX   512                 /* the apps' icons are 50-110 bytes */

typedef struct {
    char     file[64];
    uint32_t size, mtime;
    char     id[40], name[40], icon[16];
    int32_t  icon_vec;
    uint32_t color_a, color_b, flags;
    int32_t  order;
    uint16_t aic_len;
    uint8_t  aic[CACHE_AIC_MAX];
} cache_rec_t;

typedef struct {
    uint32_t magic, version;
    char     fw[24];                        /* the firmware's ELF sha */
    uint32_t count;
} cache_head_t;

static cache_rec_t *s_cache_old, *s_cache_new;
static int s_cache_old_n, s_cache_new_n;
static bool s_cache_dirty;
static bool s_cache_stale;      /* s_cache_old is another firmware's */

static void cache_path(char *out, size_t n)
{
    snprintf(out, n, "%s/apps.cache", aos_hal_path_data());
}

static void cache_fw(char *out, size_t n)
{
    memset(out, 0, n);
    esp_app_get_elf_sha256(out, n);
}

static void cache_load(void)
{
    s_cache_old = heap_caps_calloc(MAX_DYNAPPS, sizeof(cache_rec_t), MALLOC_CAP_SPIRAM);
    s_cache_new = heap_caps_calloc(MAX_DYNAPPS, sizeof(cache_rec_t), MALLOC_CAP_SPIRAM);
    s_cache_old_n = s_cache_new_n = 0;
    s_cache_dirty = false;
    s_cache_stale = false;
    if (!s_cache_old || !s_cache_new) return;
    char path[96];
    cache_path(path, sizeof path);
    FILE *f = fopen(path, "rb");
    if (!f) {
        s_cache_dirty = true;
        return;
    }
    cache_head_t h;
    char fw[24];
    cache_fw(fw, sizeof fw);
    if (fread(&h, sizeof h, 1, f) == 1 && h.magic == CACHE_MAGIC && h.version == CACHE_VERSION &&
        h.count <= MAX_DYNAPPS && fread(s_cache_old, sizeof(cache_rec_t), h.count, f) == h.count) {
        s_cache_old_n = (int)h.count;
        s_cache_stale = memcmp(h.fw, fw, sizeof fw) != 0;
    }
    if (!s_cache_old_n || s_cache_stale) {
        /* another firmware's records are only a last resort, for a .so the
         * scan could not open for lack of memory (aos_dynapp_scan) */
        ESP_LOGI(TAG, "apps cache: none for this firmware, every .so is opened once");
        s_cache_dirty = true;
    }
    fclose(f);
}

static const cache_rec_t *cache_find_any(const char *file, uint32_t size, uint32_t mtime);

static const cache_rec_t *cache_find(const char *file, uint32_t size, uint32_t mtime)
{
    return s_cache_stale ? NULL : cache_find_any(file, size, mtime);
}

static const cache_rec_t *cache_find_any(const char *file, uint32_t size, uint32_t mtime)
{
    for (int i = 0; i < s_cache_old_n; i++) {
        const cache_rec_t *r = &s_cache_old[i];
        if (!strcmp(r->file, file) && r->size == size && r->mtime == mtime) return r;
    }
    return NULL;
}

static void cache_keep(const cache_rec_t *r)
{
    if (s_cache_new && s_cache_new_n < MAX_DYNAPPS) s_cache_new[s_cache_new_n++] = *r;
}

/* What the dlopen just registered for a one-app module, for next time. */
static void cache_note(const char *file, uint32_t size, uint32_t mtime, const dynapp_t *slot)
{
    if (!s_cache_new || s_cache_new_n >= MAX_DYNAPPS) return;
    cache_rec_t *r = &s_cache_new[s_cache_new_n];
    memset(r, 0, sizeof *r);
    snprintf(r->file, sizeof r->file, "%s", file);
    r->size = size;
    r->mtime = mtime;
    snprintf(r->id, sizeof r->id, "%s", slot->id);
    snprintf(r->name, sizeof r->name, "%s", slot->name);
    snprintf(r->icon, sizeof r->icon, "%s", slot->icon);
    const aos_app_t *a = aos_ui_app_find(slot->id);
    if (!a) return;
    r->icon_vec = (int32_t)a->desc.icon_vec;
    r->color_a = a->desc.color_a;
    r->color_b = a->desc.color_b;
    r->flags = a->desc.flags;
    r->order = a->desc.order;
    size_t len = 0;
    const uint8_t *aic = aos_icon_app_ops(slot->id, &len);
    if (aic && len <= CACHE_AIC_MAX) {
        memcpy(r->aic, aic, len);
        r->aic_len = (uint16_t)len;
    }
    s_cache_new_n++;
    s_cache_dirty = true;
}

static void cache_save(void)
{
    if (s_cache_new && (s_cache_dirty || s_cache_new_n != s_cache_old_n)) {
        char path[96], tmp[104];
        cache_path(path, sizeof path);
        snprintf(tmp, sizeof tmp, "%s.part", path);
        FILE *f = fopen(tmp, "wb");
        if (f) {
            cache_head_t h = { CACHE_MAGIC, CACHE_VERSION, { 0 }, (uint32_t)s_cache_new_n };
            cache_fw(h.fw, sizeof h.fw);
            bool ok = fwrite(&h, sizeof h, 1, f) == 1 &&
                      fwrite(s_cache_new, sizeof(cache_rec_t), (size_t)s_cache_new_n, f) == (size_t)s_cache_new_n;
            ok = fclose(f) == 0 && ok;
            if (ok) {
                remove(path);
                ok = rename(tmp, path) == 0;
            }
            ESP_LOGI(TAG, "apps cache: %d app(s) written%s", s_cache_new_n, ok ? "" : " - FAILED");
        }
    }
    free(s_cache_old);
    free(s_cache_new);
    s_cache_old = s_cache_new = NULL;
}

static void cache_desc(const cache_rec_t *r, aos_app_desc_t *d)
{
    memset(d, 0, sizeof *d);
    d->id = r->id;
    d->name = r->name;
    d->icon = r->icon[0] ? r->icon : NULL;
    d->icon_vec = (aos_icon_id_t)r->icon_vec;
    d->color_a = r->color_a;
    d->color_b = r->color_b;
    d->flags = r->flags;
    d->order = r->order;
}

int aos_dynapp_scan(void)
{
    /* Before anything else: the reservation is asked for with the heap still
     * whole. The scan opens and closes each .so, and afterwards WiFi starts,
     * which takes some 35 KB of this same memory. Asking for it later would be
     * asking for it already fragmented, which is precisely what we want to
     * avoid. */
#if !AOS_CODE_IN_PSRAM
    pool_init();
#else
    ESP_LOGI(TAG, "apps' code runs from PSRAM: no internal reservation");
#endif

    int64_t ti = esp_timer_get_time();
    sym_index_build();
    ESP_LOGI(TAG, "symbol index: %d entries, %u ms", s_sym_count,
             (unsigned)((esp_timer_get_time() - ti) / 1000));
    elf_set_symbol_resolver(resolver);

    ESP_LOGI(TAG, "executable memory: %u B free, largest block %u B",
             (unsigned)heap_caps_get_free_size(MALLOC_CAP_EXEC),
             (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_EXEC));

    DIR *dir = opendir(AOS_DYNAPP_DIR);
    if (!dir) {
        ESP_LOGI(TAG, "there is no %s folder, no dynamic apps", AOS_DYNAPP_DIR);
        return 0;
    }

    /* The loader logs every symbol of every module at INFO: hundreds of lines
     * per .so, which is what made the 16 KB log ring forget the boot before
     * anyone could read it. Its warnings and errors still come through. */
    static const char *const LOUD[] = { "ELF", "DLMOD", "DLFCN", "elf_arch",
                                        "ELF_SYMBOL", "elf_s3mmu" };
    for (size_t i = 0; i < sizeof(LOUD) / sizeof(LOUD[0]); i++) {
        esp_log_level_set(LOUD[i], ESP_LOG_WARN);
    }

    /* Two passes. The first registers ONE app of every module; the second
     * the rest of the modules that declare several (lua.so, one app per
     * script). Before, readdir's order decided: with 200 scripts on the card
     * lua.so came before turbo.so, took the slots, and turbo and monsterhop
     * were the ones left out. A card full of scripts must never push a real
     * app out of the launcher. Timed, since every .so is opened here and this
     * is where a card with many apps costs boot time (docs/APPS-P4.md, "Measured"). */
    memset(&s_scan_cost, 0, sizeof(s_scan_cost));
    s_resolve_us = 0;
    s_resolve_calls = 0;
    int64_t t0 = esp_timer_get_time();
    enum { DEFERRED_MAX = 8, OOM_MAX = 8 };
    char deferred[DEFERRED_MAX][64];
    int n_deferred = 0;
    /* modules that could not be opened for lack of memory: once more at the
     * end, and from another firmware's cache if that fails too */
    struct { char file[64]; uint32_t size, mtime; } oom[OOM_MAX];
    int n_oom = 0;

    int loaded = 0;
    struct dirent *item;
    /* how many there are, for the boot screen's bar */
    int files = 0, seen = 0;
    while ((item = readdir(dir)) != NULL)
        if (item->d_name[0] != '.' && ends_with_so(item->d_name)) files++;
    rewinddir(dir);
    if (aos_hal_lock(1000)) {
        aos_ui_hold_home(true);
        aos_hal_unlock();
    }
    cache_load();
    int from_cache = 0, opened = 0;
    while ((item = readdir(dir)) != NULL) {
        if (item->d_name[0] == '.' || !ends_with_so(item->d_name)) {
            continue;
        }
        if (aos_hal_lock(1000)) {
            aos_ui_boot_progress(seen++, files + 1);
            aos_hal_unlock();
        }
        char full[192];
        snprintf(full, sizeof full, "%s/%s", AOS_DYNAPP_DIR, item->d_name);
        struct stat st;
        uint32_t size = 0, mtime = 0;
        if (stat(full, &st) == 0) {
            size = (uint32_t)st.st_size;
            mtime = (uint32_t)st.st_mtime;
        }
        /* described before, and not changed since: kept for the batch below */
        const cache_rec_t *hit = size ? cache_find(item->d_name, size, mtime) : NULL;
        if (hit) {
            cache_keep(hit);
            continue;
        }
        uint32_t total = 0;
        int before = s_count;
        if (register_apps(item->d_name, true, &total) > 0) {
            loaded++;
            opened++;
            if (total > 1 && n_deferred < DEFERRED_MAX) {
                snprintf(deferred[n_deferred++], sizeof(deferred[0]), "%s", item->d_name);
            }
            if (total == 1 && size && s_count == before + 1) cache_note(item->d_name, size, mtime, &s_apps[before]);
        } else if (s_oom && n_oom < OOM_MAX) {
            snprintf(oom[n_oom].file, sizeof oom[n_oom].file, "%.63s", item->d_name);
            oom[n_oom].size = size;
            oom[n_oom].mtime = mtime;
            n_oom++;
        }
    }
    closedir(dir);
    /* The PSRAM at boot is the most it will ever be, but the scan runs
     * beside the boot's own allocations (the home and lock photos decoded,
     * the radio, Bluetooth) and a big .so (cas.so, 5.3 MB: about 11 MB at
     * once) can land on a moment without a block for it (2026-11-08: the
     * app was simply missing from the home screen). Once more now; and if
     * it still does not fit, the record another firmware left (same file,
     * size and date) puts it on the home screen anyway, and its code is
     * loaded when it is opened, with the PSRAM of a quiet board. That record
     * is not carried into the new cache: the next boot opens it for real. */
    /* the photos split the PSRAM: they go for the retries, and the home
     * screen's is asked for again after them (the lock screen's comes back
     * when the screen locks) */
    bool room = false;
    if (n_oom && aos_hal_lock(1000)) {
        room = aos_ui_make_room() > 0;
        aos_hal_unlock();
    }
    for (int i = 0; i < n_oom; i++) {
        uint32_t total = 0;
        int before = s_count;
        ESP_LOGW(TAG, "%s: out of memory while scanning, trying again", oom[i].file);
        if (register_apps(oom[i].file, true, &total) > 0) {
            loaded++;
            opened++;
            if (total > 1 && n_deferred < DEFERRED_MAX) {
                snprintf(deferred[n_deferred++], sizeof(deferred[0]), "%.63s", oom[i].file);
            }
            if (total == 1 && oom[i].size && s_count == before + 1)
                cache_note(oom[i].file, oom[i].size, oom[i].mtime, &s_apps[before]);
            continue;
        }
        const cache_rec_t *r = oom[i].size ? cache_find_any(oom[i].file, oom[i].size, oom[i].mtime) : NULL;
        if (!r) {
            ESP_LOGE(TAG, "%s left out: no memory to describe it and no record of it", oom[i].file);
            continue;
        }
        aos_app_desc_t d;
        cache_desc(r, &d);
        bool locked = false;
        int in_batch = 0;
        if (register_one(r->file, 0, &d, r->aic, r->aic_len, &locked, &in_batch)) {
            loaded++;
            from_cache++;
            ESP_LOGW(TAG, "%s registered from an older cache record: it loads when opened", oom[i].file);
        }
        if (locked) aos_hal_unlock();
    }
    if (room && aos_hal_lock(1000)) {
        aos_ui_room_back();
        aos_hal_unlock();
    }
    /* the ones from the cache, in batches under one lock: nothing opened */
    {
        bool locked = false;
        int in_batch = 0;
        for (int i = 0; i < s_cache_new_n; i++) {
            const cache_rec_t *r = &s_cache_new[i];
            if (find_by_id(r->id)) continue;            /* opened above */
            aos_app_desc_t d;
            cache_desc(r, &d);
            if (register_one(r->file, 0, &d, r->aic, r->aic_len, &locked, &in_batch)) {
                loaded++;
                from_cache++;
            }
        }
        if (locked) aos_hal_unlock();
    }
    cache_save();
    ESP_LOGI(TAG, "apps: %d from the cache, %d opened to be described", from_cache, opened);
    int64_t t1 = esp_timer_get_time();

    for (int i = 0; i < n_deferred; i++) {
        uint32_t total = 0;
        register_apps(deferred[i], false, &total);
    }
    /* the home screen once, with every app in it */
    if (aos_hal_lock(2000)) {
        aos_ui_boot_progress(files, files + 1);
        aos_ui_hold_home(false);
        aos_hal_unlock();
    }
    int64_t t2 = esp_timer_get_time();

    ESP_LOGI(TAG, "scan: %d modules, %d apps, %u ms (modules %u ms, extra apps %u ms; "
                  "open %u, of it symbols %u for %u lookups; lock wait %u, register %u)",
             loaded, s_count, (unsigned)((t2 - t0) / 1000),
             (unsigned)((t1 - t0) / 1000), (unsigned)((t2 - t1) / 1000),
             (unsigned)(s_scan_cost.open_us / 1000), (unsigned)(s_resolve_us / 1000),
             (unsigned)s_resolve_calls, (unsigned)(s_scan_cost.lock_us / 1000),
             (unsigned)(s_scan_cost.reg_us / 1000));
    return loaded;
}
